import { BarChart, Bar, XAxis, YAxis, CartesianGrid, Tooltip, ResponsiveContainer } from 'recharts'
import { AlertCircle, FileCheck, CheckCircle2, ShieldAlert, AlertTriangle } from 'lucide-react'

const PredictionResult = ({ prediction, onSubmitReview }) => {
  if (!prediction) return null

  const severityLabels = ['0 - No DR', '1 - Mild', '2 - Moderate', '3 - Severe', '4 - Proliferative DR']
  const drClass = prediction.predicted_class ?? prediction.dr_class ?? 0
  const predLabel = prediction.predicted_label || prediction.prediction || severityLabels[drClass]
  const confidence = Number(prediction.confidence ?? 0)
  const isDemo = Boolean(prediction.is_demo_mode || prediction.is_demo)

  const uncLevel = prediction.uncertainty_level || (prediction.uncertainty_std < 0.05 ? 'Low' : 'Medium')

  // User-mandated Stage B User-Facing Status
  const summaryStatus = prediction.summary_status || (
    prediction.is_gradable === false || confidence < 0.60 || prediction.ood_detected || uncLevel === 'High'
      ? 'INCONCLUSIVE — CLINICIAN REVIEW REQUIRED'
      : drClass > 0
      ? 'DR DETECTED'
      : 'NO DR DETECTED'
  )

  let probList = []
  if (Array.isArray(prediction.class_probabilities) && prediction.class_probabilities.length === 5) {
    probList = prediction.class_probabilities
  } else if (prediction.probabilities && typeof prediction.probabilities === 'object') {
    probList = ['No DR', 'Mild', 'Moderate', 'Severe', 'Proliferative DR'].map(
      k => prediction.probabilities[k] ?? 0
    )
  }

  const chartData = ['No DR', 'Mild', 'Moderate', 'Severe', 'Proliferative'].map((name, idx) => ({
    name,
    prob: Math.round((probList[idx] || 0) * 100)
  }))

  const getConfidenceColor = (conf) => {
    if (conf >= 0.8) return 'text-[#A8C4B8]'
    if (conf >= 0.5) return 'text-[#FBBF24]'
    return 'text-[#F87171]'
  }

  return (
    <div className="bg-[#121212]/95 backdrop-blur-md rounded-xl border border-[#292929] overflow-hidden shadow-lg">
      {isDemo && (
        <div className="bg-[#191919] text-[#FBBF24] px-4 py-2.5 text-xs text-center border-b border-[#292929] flex items-center justify-center gap-2">
          <ShieldAlert className="w-4 h-4 text-[#FBBF24]" />
          <strong>Simulation Mode:</strong> Results generated by baseline evaluation weights.
        </div>
      )}
      {prediction.is_gradable === false && (
        <div className="bg-rose-500/10 text-[#F87171] px-4 py-3 text-xs border-b border-rose-500/25 flex items-start gap-2.5">
          <AlertCircle className="w-4 h-4 text-[#F87171] shrink-0 mt-0.5" />
          <div>
            <strong className="block text-[#F5F0E6] text-xs font-semibold">Ungradable Image Quality Warning</strong>
            <span className="text-[#D0CCC3]">{prediction.quality_warnings && prediction.quality_warnings.length > 0 ? prediction.quality_warnings.join('. ') : 'Retinal fundus image violates acquisition standards.'}</span>
            <span className="block mt-1 font-medium text-[#F87171]">Clinical Recommendation: Repeat photograph acquisition or manual ophthalmology examination.</span>
          </div>
        </div>
      )}
      {prediction.ood_detected && (
        <div className="bg-amber-500/10 text-[#FBBF24] px-4 py-2.5 text-xs border-b border-amber-500/25 flex items-center gap-2">
          <ShieldAlert className="w-4 h-4 text-[#FBBF24] shrink-0" />
          <div>
            <strong>Distribution Shift:</strong> Extreme activation magnitude detected. Softmax confidence calibrated to prevent overconfidence.
          </div>
        </div>
      )}
      
      <div className="p-6">
        <div className="flex justify-between items-center mb-6 border-b border-[#292929] pb-3">
          <h2 className="text-lg font-bold text-[#F5F0E6]">AI Screening Results</h2>
          <span className="text-xs font-medium px-2.5 py-1 bg-[#191919] text-[#81958D] border border-[#292929] rounded-full">
            Model: {prediction.model_version || 'EfficientNet-B3'}
          </span>
        </div>
        
        <div className="grid grid-cols-1 md:grid-cols-2 gap-8">
          <div>
            {/* Primary User-Facing Stage B Classification Result */}
            <div className="mb-5">
              {summaryStatus === 'DR DETECTED' && (
                <div className="p-4 rounded-xl bg-rose-500/10 border border-rose-500/30 text-[#F87171] text-sm flex items-center gap-3">
                  <AlertCircle className="w-5 h-5 text-[#F87171] flex-shrink-0" />
                  <div>
                    <span className="block font-bold text-base text-[#F5F0E6] tracking-wide">DR DETECTED</span>
                    <span className="text-xs font-normal text-[#D0CCC3]">Diabetic retinopathy pathology identified on retinal fundus examination.</span>
                  </div>
                </div>
              )}
              {summaryStatus === 'NO DR DETECTED' && (
                <div className="p-4 rounded-xl bg-[#81958D]/15 border border-[#81958D]/35 text-[#A8C4B8] text-sm flex items-center gap-3">
                  <CheckCircle2 className="w-5 h-5 text-[#A8C4B8] flex-shrink-0" />
                  <div>
                    <span className="block font-bold text-base text-[#F5F0E6] tracking-wide">NO DR DETECTED</span>
                    <span className="text-xs font-normal text-[#D0CCC3]">No radiographic signs of diabetic retinopathy detected on valid retinal photograph.</span>
                  </div>
                </div>
              )}
              {summaryStatus === 'INCONCLUSIVE — CLINICIAN REVIEW REQUIRED' && (
                <div className="p-4 rounded-xl bg-amber-500/10 border border-amber-500/30 text-[#FBBF24] text-sm flex items-center gap-3">
                  <AlertTriangle className="w-5 h-5 text-[#FBBF24] flex-shrink-0" />
                  <div>
                    <span className="block font-bold text-base text-[#F5F0E6] tracking-wide">INCONCLUSIVE — CLINICIAN REVIEW REQUIRED</span>
                    <span className="text-xs font-normal text-[#D0CCC3]">Model confidence insufficient, acquisition defect, or high prediction variance.</span>
                  </div>
                </div>
              )}
            </div>

            <div className="mb-6 p-4 rounded-xl bg-[#191919] border border-[#292929]">
              <p className="text-[11px] font-semibold text-[#85817A] uppercase tracking-wider mb-1">Detailed Severity Grade</p>
              <h3 className="text-2xl font-bold text-[#F5F0E6]">{predLabel}</h3>
              <p className="text-xs text-[#85817A] mt-1">Class {drClass} of 4 (International Clinical DR Scale)</p>
            </div>
            
            <div className="mb-6 p-4 rounded-xl bg-[#191919] border border-[#292929]">
              <p className="text-[11px] font-semibold text-[#85817A] uppercase tracking-wider mb-1">Model Confidence</p>
              <div className="flex items-end justify-between">
                <span className={`text-2xl font-bold ${getConfidenceColor(confidence)}`}>
                  {(confidence * 100).toFixed(1)}%
                </span>
                <span className={`px-2.5 py-0.5 rounded text-[11px] font-medium ${
                  uncLevel === 'Low' ? 'bg-[#81958D]/15 text-[#A8C4B8] border border-[#81958D]/30' : 'bg-amber-500/15 text-[#FBBF24] border border-amber-500/30'
                }`}>
                  {uncLevel} Uncertainty
                </span>
              </div>
              <div className="w-full bg-[#0F0F0F] h-2 mt-3 rounded-full overflow-hidden border border-[#292929]">
                <div 
                  className={`h-full transition-all duration-500 ${
                    confidence >= 0.8 ? 'bg-[#81958D]' : confidence >= 0.5 ? 'bg-amber-500' : 'bg-rose-500'
                  }`} 
                  style={{ width: `${Math.min(confidence * 100, 100)}%` }}
                />
              </div>
            </div>

            {onSubmitReview && (
              <button 
                onClick={onSubmitReview}
                className="w-full flex justify-center items-center px-5 py-3 bg-[#E8E1D5] hover:bg-[#F5F0E6] text-[#111111] font-semibold rounded-lg transition text-xs cursor-pointer shadow-sm"
              >
                <FileCheck className="w-4 h-4 mr-2" />
                Submit for Clinical Review
              </button>
            )}
          </div>
          
          <div>
            <p className="text-xs font-semibold text-[#85817A] uppercase tracking-wider mb-3">5-Class Softmax Probability Distribution</p>
            <div className="h-64 w-full bg-[#191919] p-3 rounded-xl border border-[#292929]">
              <ResponsiveContainer width="100%" height="100%">
                <BarChart data={chartData} margin={{ top: 10, right: 10, left: -20, bottom: 5 }}>
                  <CartesianGrid strokeDasharray="3 3" vertical={false} stroke="#292929" />
                  <XAxis dataKey="name" axisLine={false} tickLine={false} tick={{ fontSize: 11, fill: '#85817A' }} />
                  <YAxis axisLine={false} tickLine={false} tick={{ fontSize: 11, fill: '#85817A' }} domain={[0, 100]} tickFormatter={v => `${v}%`} />
                  <Tooltip 
                    formatter={(val) => [`${val}%`, 'Probability']}
                    contentStyle={{ backgroundColor: '#121212', borderColor: '#292929', borderRadius: '6px', color: '#F5F0E6', fontSize: '11px' }}
                  />
                  <Bar dataKey="prob" fill="#81958D" radius={[4, 4, 0, 0]} />
                </BarChart>
              </ResponsiveContainer>
            </div>
            
            <div className="mt-3 grid grid-cols-5 gap-1.5 text-[11px] text-center text-[#85817A]">
              {chartData.map((d, i) => (
                <div key={i} className={`p-2 rounded-lg border ${i === drClass ? 'bg-[#191919] border-[#81958D] font-bold text-[#F5F0E6]' : 'bg-[#121212] border-[#292929]'}`}>
                  <div className="truncate">{d.name}</div>
                  <div className="mt-0.5 text-[#D0CCC3]">{d.prob}%</div>
                </div>
              ))}
            </div>
          </div>
        </div>
      </div>
    </div>
  )
}

export default PredictionResult
